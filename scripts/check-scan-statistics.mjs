import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import assert from 'node:assert/strict';
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/scan-statistics.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, Intl, Date });
const { calculateScanStatistics: calculate, completedScanDay } = exports;
const users = [{ id: 'a', name: 'A', email: 'a@example.test', role: 'Editor' }, { id: 'b', name: 'B', email: 'b@example.test', role: 'Administrator' }];
const job = (id, userId, pages, extra = {}) => ({ id, userId, provider: 'bridge', status: 'completed', createdAt: '2026-10-27T08:00:00Z', updatedAt: '2026-10-27T09:00:00Z', result: { pageCount: pages }, ...extra });
const jobs = [job('1','a',2),job('2','a',5),job('3','b',1),job('4','b',3,{status:'failed'}),job('5','b',9,{status:'cancelled'}),job('6','b',4,{status:'processing'}),job('7','b',4,{status:'queued'}),job('8','b',4,{status:'scanning'}),job('9','b',50,{provider:'demo'}),job('1','a',2),job('10','a',undefined),job('11','former',3)];
const result = calculate(users,jobs);
assert.equal(result.totals.completedScans,5);
assert.equal(result.totals.pagesScanned,11);
assert.equal(result.totals.unknownPageCounts,1);
assert.equal(result.totals.usersWithScans,3);
assert.equal(result.timeline.reduce((sum,point)=>sum+point.completedScans,0),5);
assert.equal(result.timeline.reduce((sum,point)=>sum+point.pagesScanned,0),11);
assert.equal(result.timeline.find(point=>point.userId==='a').completedScans,3);
assert.equal(result.undatedScans,0);
assert.equal(result.users[0].userId,'a');
assert.equal(result.users[0].completedScans,3);
assert.equal(result.users[0].pagesScanned,7);
assert.equal(result.users.find(row=>row.userId==='former').name,'Former account');
assert.equal(calculate(users,[]).users.length,2);
assert(calculate(users,[]).users.every(row=>row.completedScans===0 && row.pagesScanned===0));
assert.equal(completedScanDay('2026-10-26T22:30:00Z'),'2026-10-27');
assert.equal(completedScanDay('invalid'),'');
const boundary = [job('a','a',2,{updatedAt:'2026-10-26T22:30:00Z'}),job('b','a',3,{updatedAt:'2026-10-27T22:30:00Z'}),job('c','a',1,{updatedAt:'invalid'})];
assert.equal(calculate(users,boundary,{from:'2026-10-27',to:'2026-10-27'}).totals.pagesScanned,2);
assert.equal(calculate(users,boundary,{to:'2026-10-26'}).totals.completedScans,0);
assert.equal(calculate(users,boundary).totals.completedScans,3);
assert.equal(calculate(users,boundary).undatedScans,1);
assert.equal(calculate(users,boundary,{from:'2026-10-27',to:'2026-10-27'}).timeline.length,1);
assert.equal(calculate(users,[job('bad','a',-1),job('fraction','a',1.5)]).totals.unknownPageCounts,2);
assert.equal(calculate(users,[job('1','a',2)]).users[0].lastScanAt,'2026-10-27T09:00:00Z');
console.log('Scan statistics passed: per-user counts, completed-only jobs, deduplication, missing pages, former/zero-activity users, and Beirut date boundaries.');
const timelineExports={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/statistics-timeline.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:timelineExports,Date});
const build=timelineExports.buildScanTimeline;
const days=[{date:'2026-10-25',userId:'a',completedScans:2,pagesScanned:4},{date:'2026-10-27',userId:'a',completedScans:1,pagesScanned:2},{date:'2026-10-27',userId:'b',completedScans:3,pagesScanned:9}];
const daily=build(days,['a','b'],'2026-10-25','2026-10-27','day');
assert.equal(daily.points.length,3);
assert.equal(daily.points[1].completedScans,0);
assert.equal(daily.points[2].pagesScanned,11);
assert.equal(build(days,['a'],'2026-10-25','2026-10-27','day').points[2].pagesScanned,2);
assert.equal(build(days,['a','b'],'2026-10-26','2026-10-27','month').points[0].completedScans,4);
assert.equal(build(days,['a','b'],'2026-01-01','2026-10-27','day').grouping,'month');
assert.equal(build(days,['a'],'1900-01-01','2026-10-27','day').points.length,120);
assert.equal(build(days,['a'],'1900-01-01','2026-10-27','day').limited,true);
assert.equal(build([],['a'],'','','day').points.length,0);
assert.equal(build(undefined,['a'],'2026-10-25','2026-10-27','day').points.length,0);
assert.equal(build(null,['a'],'2026-10-25','2026-10-27','day').points.length,0);
assert.equal(build([],['a'],'2024-02-28','2024-03-01','day').points.length,3);
console.log('Timeline passed: daily/monthly aggregation, user/date filters, zero gaps, leap days, invalid dates excluded and bounded long histories.');
