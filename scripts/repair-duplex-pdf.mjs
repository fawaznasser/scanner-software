import { pdf } from './scanner-pdf.mjs';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
const database = new DatabaseSync('.data/dms.sqlite');
const current = JSON.parse(readFileSync('.data/scanner-bridge/current-test.json','utf8'));
const job = JSON.parse(database.prepare('SELECT record FROM scan_jobs WHERE id=?').get(current.jobId).record);
if(job.result?.fileName !== 'HP_Duplex_Test.pdf' || job.result.pageCount !== 2) throw new Error('Not the confirmed duplex test');
const folder=path.join('.data','scanner-bridge',job.providerJobId);
const repair=JSON.parse(readFileSync(path.join(folder,'repair.json'),'utf8').replace(/^\uFEFF/,''));
if(repair.documentId!==job.result.documentId) throw new Error('Document mismatch');
const row=database.prepare('SELECT * FROM documents WHERE id=?').get(repair.documentId);
const record=JSON.parse(row.record);
if(record.name!=='HP_Duplex_Test.pdf') throw new Error('Document name mismatch');
const file=path.join('.data','documents',row.file_key);
copyFileSync(file,path.join(folder,'original-invalid-test.pdf'),0);
const bytes=pdf(repair.pages,300);
writeFileSync(file,bytes);
writeFileSync(path.join(folder,'result.pdf'),bytes);
const before=record.size;record.size=`${(bytes.length/1024/1024).toFixed(2)} MB`;
job.result.sizeBytes=bytes.length;
database.prepare('UPDATE documents SET record=? WHERE id=?').run(JSON.stringify(record),repair.documentId);
database.prepare('UPDATE scan_jobs SET record=? WHERE id=?').run(JSON.stringify(job),job.id);
const original=JSON.parse(database.prepare('SELECT record FROM audit_logs WHERE document_id=? ORDER BY timestamp LIMIT 1').get(repair.documentId).record);
const event={...original,id:randomUUID(),action:'file-updated',timestamp:new Date().toISOString(),description:`Repaired image encoding for assisted duplex test ${record.documentNumber} (${record.name}); both captured sides preserved.`,file:{...original.file,changes:[{field:'PDF image encoding',before:'Driver bitmap incorrectly labeled JPEG',after:'Converted JPEG images; two PDF pages'}]}};
database.prepare('INSERT INTO audit_logs(id,timestamp,user_id,document_id,record) VALUES(?,?,?,?,?)').run(event.id,event.timestamp,event.userId,repair.documentId,JSON.stringify(event));
database.close();console.log(JSON.stringify({documentId:repair.documentId,bytes:bytes.length,previousSize:before,pages:repair.pages.length}));
